"""Convert an uncompressed 24-bit BMP into a C array of RGB888 pixels.

Usage: python bmp_to_c.py couple.bmp ../../phase_03/sample_image.c

The image is stored row by row, top to bottom, 3 bytes per pixel (R, G, B),
which is the same layout a camera driver typically delivers in RGB888 mode.
No external packages are needed.
"""
import os
import struct
import sys


def read_bmp_rgb888(path):
    with open(path, "rb") as f:
        data = f.read()

    if data[0:2] != b"BM":
        raise ValueError("not a BMP file")
    pixel_offset = struct.unpack_from("<I", data, 10)[0]
    width, height, _, bpp, compression = struct.unpack_from("<iiHHI", data, 18)
    if bpp != 24 or compression != 0:
        raise ValueError("only uncompressed 24-bit BMP is supported")

    # BMP rows are stored bottom-up (if height > 0), BGR, padded to 4 bytes
    top_down = height < 0
    height = abs(height)
    row_size = (width * 3 + 3) & ~3

    rgb = bytearray()
    for y in range(height):
        src_row = y if top_down else height - 1 - y
        row = data[pixel_offset + src_row * row_size:][:width * 3]
        for x in range(width):
            b, g, r = row[x * 3:x * 3 + 3]
            rgb += bytes((r, g, b))
    return width, height, rgb


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    bmp_path, c_path = sys.argv[1], sys.argv[2]
    width, height, rgb = read_bmp_rgb888(bmp_path)

    with open(c_path, "w", newline="\n") as f:
        f.write(f"/* Generated by misc/samples/bmp_to_c.py from {os.path.basename(bmp_path)} */\n")
        f.write('#include "sample_image.h"\n\n')
        f.write(f"#if (SAMPLE_IMAGE_WIDTH != {width}) || (SAMPLE_IMAGE_HEIGHT != {height})\n")
        f.write("#error \"sample_image.h dimensions do not match the generated image\"\n")
        f.write("#endif\n\n")
        f.write("const uint8_t sample_image[SAMPLE_IMAGE_WIDTH * SAMPLE_IMAGE_HEIGHT * 3] = {\n")
        for i in range(0, len(rgb), 16):
            f.write("    " + ", ".join(f"0x{v:02x}" for v in rgb[i:i + 16]) + ",\n")
        f.write("};\n")
    print(f"Wrote {c_path}: {width}x{height} RGB888, {len(rgb)} bytes")


if __name__ == "__main__":
    main()
